using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PureMarkup.Blazor.Generators;

/// <summary>
/// Generates element factories (<c>H.Div()</c>), typed element handles, attribute methods, enums and event methods from
/// <c>html.data</c> (an AdditionalFile of the PureMarkup.Blazor project; format in the file header). Runs only where that
/// file is present, i.e. when the library itself is compiled.
/// </summary>
[Generator]
public sealed class HtmlGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(static f => Path.GetFileName(f.Path).Equals("html.data", StringComparison.OrdinalIgnoreCase))
            .Select(static (f, ct) => f.GetText(ct)?.ToString() ?? "");
        context.RegisterSourceOutput(files, static (spc, text) =>
        {
            var data = HtmlData.Parse(text);
            foreach (var (name, source) in Emit(data)) spc.AddSource(name, SourceText.From(source, Encoding.UTF8));
        });
    }

    private const string Ns = "global::PureMarkup.Blazor";
    private const string Header = "// <auto-generated/> from Html/html.data by PureMarkup.Blazor.Generators.HtmlGenerator\n#nullable enable\nusing PureMarkup.Blazor.Rendering;\n\nnamespace PureMarkup.Blazor;\n\n";

    internal static IEnumerable<(string Name, string Source)> Emit(HtmlData d)
    {
        // ---- enums ----
        var sb = new StringBuilder(Header);
        foreach (var e in d.Enums)
        {
            sb.Append("/// <summary>Values of HTML attributes that use <c>").Append(e.Name).AppendLine("</c>.</summary>");
            sb.Append("public enum ").AppendLine(e.Name).AppendLine("{");
            foreach (var (html, cs) in e.Members) sb.Append("    /// <summary><c>").Append(Xml(html)).Append("</c></summary>\n    ").Append(cs).AppendLine(",");
            sb.AppendLine("}").AppendLine();
        }
        sb.AppendLine("internal static class HtmlEnums").AppendLine("{");
        foreach (var e in d.Enums)
        {
            sb.Append("    public static string ToHtml(this ").Append(Ns).Append('.').Append(e.Name).AppendLine(" value) => value switch").AppendLine("    {");
            foreach (var (html, cs) in e.Members) sb.Append("        ").Append(Ns).Append('.').Append(e.Name).Append('.').Append(cs).Append(" => \"").Append(html).AppendLine("\",");
            sb.AppendLine("        _ => throw new global::System.ArgumentOutOfRangeException(nameof(value)),").AppendLine("    };");
        }
        sb.AppendLine("}").AppendLine();
        sb.AppendLine("internal static class HtmlData").AppendLine("{");
        sb.Append("    public static bool IsVoid(string tag) => tag switch { ");
        sb.Append(string.Join(" or ", d.Elements.Where(e => e.Void).Select(e => "\"" + e.Tag + "\"")));
        sb.AppendLine(" => true, _ => false };").AppendLine("}");
        yield return ("Html.Enums.g.cs", sb.ToString());

        // ---- element handles + factories ----
        // Attribute name -> elements that have it (non-global).
        var byAttr = new Dictionary<string, List<(HtmlElement El, HtmlAttr Attr)>>(StringComparer.Ordinal);
        foreach (var el in d.Elements)
            foreach (var a in el.Attrs)
            {
                if (!byAttr.TryGetValue(a.Html, out var list)) byAttr[a.Html] = list = new();
                list.Add((el, a));
            }

        sb = new StringBuilder(Header);
        foreach (var a in byAttr.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            var cs = a.Value[0].Attr.Cs;
            sb.Append("/// <summary>Elements with the <c>").Append(a.Key).AppendLine("</c> attribute.</summary>");
            sb.Append("public interface IHas").Append(cs).AppendLine(" : IElement { }");
        }
        sb.AppendLine();
        foreach (var el in d.Elements)
        {
            var type = el.Type;
            sb.Append("/// <summary>A <c>&lt;").Append(el.Tag).AppendLine("&gt;</c> element.</summary>");
            sb.Append("public readonly struct ").Append(type).Append(" : IElement");
            foreach (var a in el.Attrs) sb.Append(", IHas").Append(a.Cs);
            sb.AppendLine().AppendLine("{");
            sb.AppendLine("    private readonly Node _node;");
            sb.Append("    internal ").Append(type).AppendLine("(Node node) => _node = node;");
            sb.AppendLine("    /// <inheritdoc/>").AppendLine("    public Node Node => _node;");
            sb.AppendLine("    /// <summary>Converts to a node.</summary>");
            sb.Append("    public static implicit operator Node(").Append(type).AppendLine(" e) => e._node;");
            sb.AppendLine("}").AppendLine();
        }
        sb.AppendLine("public static partial class H").AppendLine("{");
        foreach (var el in d.Elements)
        {
            sb.Append("    /// <summary><c>&lt;").Append(el.Tag).AppendLine("&gt;</c></summary>");
            sb.Append("    public static ").Append(el.Type).Append(' ').Append(el.Method).Append("() => new(RenderArena.Current.NewNode(NodeKind.Element, \"")
              .Append(el.Tag).AppendLine("\"));");
        }
        sb.AppendLine("}").AppendLine();
        // Tags by element type, for a preset's .New().
        sb.AppendLine("internal static class ElementTags").AppendLine("{");
        sb.AppendLine("    private static readonly global::System.Collections.Generic.Dictionary<global::System.Type, string> Tags = new()").AppendLine("    {");
        foreach (var el in d.Elements)
            sb.Append("        [typeof(").Append(el.Type).Append(")] = \"").Append(el.Tag).AppendLine("\",");
        sb.AppendLine("    };");
        sb.AppendLine("    public static string? Of(global::System.Type type) => Tags.TryGetValue(type, out var tag) ? tag : null;");
        sb.AppendLine("}");
        yield return ("Html.Elements.g.cs", sb.ToString());

        // ---- attribute methods ----
        sb = new StringBuilder(Header);
        sb.AppendLine("/// <summary>Generated HTML attribute methods. Each is available only on elements that have the attribute.</summary>");
        sb.AppendLine("public static class HtmlAttributes").AppendLine("{");
        var count = 0;
        foreach (var g in d.Globals)
        {
            count += EmitAttr(sb, g, "T", "where T : struct, IElement", isGeneric: true);
            // Enum-typed globals also accept a string.
            if (g.Kind is { } k && IsEnum(d, k)) count += EmitAttr(sb, new HtmlAttr(g.Html, g.Cs, null), "T", "where T : struct, IElement", isGeneric: true);
        }
        foreach (var a in byAttr.OrderBy(k => k.Key, StringComparer.Ordinal))
        {
            var uses = a.Value;
            // The generic method takes the kind every element agrees on (or string); elements that differ get a concrete overload.
            var kinds = uses.Select(u => u.Attr.Kind).Distinct().ToList();
            var baseKind = kinds.Count == 1 && (kinds[0] is null || !IsEnum(d, kinds[0]!)) ? kinds[0] : null;
            var cs = uses[0].Attr.Cs;
            count += EmitAttr(sb, new HtmlAttr(a.Key, cs, baseKind), "T", $"where T : struct, IHas{cs}", isGeneric: true);
            foreach (var (el, attr) in uses)
                if (attr.Kind != baseKind) count += EmitAttr(sb, attr, el.Type, "", isGeneric: false);
        }
        sb.AppendLine("}");
        yield return ("Html.Attributes.g.cs", sb.ToString());

        // ---- events ----
        sb = new StringBuilder(Header);
        sb.AppendLine("/// <summary>Generated DOM event methods, one per Blazor <c>[EventHandler]</c> registration, four handler shapes each.</summary>");
        sb.AppendLine("public static class HtmlEvents").AppendLine("{");
        var events = 0;
        foreach (var ev in d.Events)
        {
            var args = ev.ArgsType switch
            {
                "EventArgs" => "global::System.EventArgs",
                "ChangeEventArgs" => "global::Microsoft.AspNetCore.Components.ChangeEventArgs",
                _ => "global::Microsoft.AspNetCore.Components.Web." + ev.ArgsType,
            };
            foreach (var handler in new[] { "global::System.Action", $"global::System.Action<{args}>", "global::System.Func<global::System.Threading.Tasks.Task>", $"global::System.Func<{args}, global::System.Threading.Tasks.Task>" })
            {
                sb.Append("    /// <summary><c>").Append(ev.Html).Append("</c> (").Append(ev.ArgsType).AppendLine(").</summary>");
                sb.Append("    public static T ").Append(ev.Cs).Append("<T>(this T el, ").Append(handler).Append(" handler) where T : struct, IElement => el.OnCore<T, ")
                  .Append(args).Append(">(\"").Append(ev.Html).AppendLine("\", handler);");
                events++;
            }
        }
        sb.AppendLine("}");
        yield return ("Html.Events.g.cs", sb.ToString());

        yield return ("Html.Counts.g.cs",
            $"// <auto-generated/>\n// elements: {d.Elements.Count}, attribute methods: {count}, event methods: {events}, enums: {d.Enums.Count}\nnamespace PureMarkup.Blazor;\n\ninternal static class HtmlCounts\n{{\n    public const int Elements = {d.Elements.Count};\n    public const int AttributeMethods = {count};\n    public const int EventMethods = {events};\n}}\n");
    }

    private static bool IsEnum(HtmlData d, string kind) => d.Enums.Any(e => e.Name == kind);

    private static int EmitAttr(StringBuilder sb, HtmlAttr a, string self, string constraint, bool isGeneric)
    {
        var (paramType, value, kind) = a.Kind switch
        {
            null => ("string?", "value", "AttrKind.String"),
            "bool" => ("bool", "value ? ElementExtensions.BoxedTrue : null", "AttrKind.Object"),
            "tf" => ("bool", "value ? \"true\" : \"false\"", "AttrKind.String"),
            "yn" => ("bool", "value ? \"yes\" : \"no\"", "AttrKind.String"),
            var e => ($"{Ns}.{e}", "value.ToHtml()", "AttrKind.String"),
        };
        var param = a.Kind == "bool" ? "bool value = true" : paramType + " value";
        sb.Append("    /// <summary><c>").Append(a.Html).AppendLine("</c></summary>");
        sb.Append("    public static ").Append(self).Append(' ').Append(a.Cs).Append(isGeneric ? "<T>" : "").Append("(this ").Append(self).Append(" el, ")
          .Append(param).Append(')').Append(constraint.Length > 0 ? " " + constraint : "").AppendLine();
        sb.AppendLine("    {");
        if (a.Kind is null && a.Html is "class" or "style")
        {
            // Additive: every .Class(...) adds a class (strings and rules alike); every .Style(...) adds declarations.
            sb.Append("        RenderArena.Current.").Append(a.Html == "class" ? "AddClass" : "AddStyle").AppendLine("(el.Node, value);");
        }
        else
        {
            sb.Append("        RenderArena.Current.AddAttr(el.Node, ").Append(kind).Append(", \"").Append(a.Html).Append("\", ").Append(value).AppendLine(");");
        }
        sb.AppendLine("        return el;").AppendLine("    }");
        return 1;
    }

    private static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;");
}

internal sealed record HtmlAttr(string Html, string Cs, string? Kind);

internal sealed record HtmlElement(string Tag, bool Void, List<HtmlAttr> Attrs)
{
    public string Method => char.ToUpperInvariant(Tag[0]) + Tag.Substring(1);
    // <i> would be "IElement", which reads as (and collides with) the interface.
    public string Type => Tag == "i" ? "ItalicElement" : Method + "Element";
}

internal sealed record HtmlEnum(string Name, List<(string Html, string Cs)> Members);

internal sealed record HtmlEvent(string Html, string Cs, string ArgsType);

internal sealed class HtmlData
{
    public List<HtmlEnum> Enums { get; } = new();
    public List<HtmlAttr> Globals { get; } = new();
    public List<HtmlElement> Elements { get; } = new();
    public List<HtmlEvent> Events { get; } = new();

    public static HtmlData Parse(string text)
    {
        var d = new HtmlData();
        foreach (var raw in text.Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line[0] == '#') continue;
            if (line.StartsWith("enum ", StringComparison.Ordinal))
            {
                var parts = line.Split(' ');
                var members = parts.Skip(2).Select(p => { var i = p.LastIndexOf('='); return (p.Substring(0, i), p.Substring(i + 1)); }).ToList();
                d.Enums.Add(new HtmlEnum(parts[1], members));
            }
            else if (line.StartsWith("global:", StringComparison.Ordinal))
            {
                d.Globals.AddRange(Attrs(line.Substring("global:".Length)));
            }
            else if (line.StartsWith("element ", StringComparison.Ordinal))
            {
                var colon = line.IndexOf(':');
                var head = line.Substring("element ".Length, colon - "element ".Length).Split(' ');
                d.Elements.Add(new HtmlElement(head[0], head.Length > 1 && head[1] == "void", Attrs(line.Substring(colon + 1)).ToList()));
            }
            else if (line.StartsWith("event ", StringComparison.Ordinal))
            {
                var parts = line.Split(' ');
                var eq = parts[1].IndexOf('=');
                d.Events.Add(new HtmlEvent(parts[1].Substring(0, eq), parts[1].Substring(eq + 1), parts[2]));
            }
        }
        return d;
    }

    private static IEnumerable<HtmlAttr> Attrs(string s)
    {
        foreach (var tok in s.Split(new[] { ' ' }, StringSplitOptions.RemoveEmptyEntries))
        {
            var eq = tok.IndexOf('=');
            var rest = tok.Substring(eq + 1);
            var colon = rest.IndexOf(':');
            yield return colon < 0
                ? new HtmlAttr(tok.Substring(0, eq), rest, null)
                : new HtmlAttr(tok.Substring(0, eq), rest.Substring(0, colon), rest.Substring(colon + 1));
        }
    }
}
