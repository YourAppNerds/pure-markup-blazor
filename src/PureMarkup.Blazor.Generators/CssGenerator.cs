using System;
using System.Collections.Generic;
using System.IO;
using System.Linq;
using System.Text;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PureMarkup.Blazor.Generators;

/// <summary>
/// Generates the typed CSS property surface (<c>CssProperties&lt;TSelf&gt;</c> methods) and keyword types from
/// <c>Css/css.data</c> (an AdditionalFile of the PureMarkup.Blazor project; format in the file header).
/// </summary>
[Generator]
public sealed class CssGenerator : IIncrementalGenerator
{
    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var files = context.AdditionalTextsProvider
            .Where(static f => Path.GetFileName(f.Path).Equals("css.data", StringComparison.OrdinalIgnoreCase))
            .Select(static (f, ct) => f.GetText(ct)?.ToString() ?? "");
        context.RegisterSourceOutput(files, static (spc, text) =>
        {
            foreach (var (name, source) in Emit(text)) spc.AddSource(name, SourceText.From(source, Encoding.UTF8));
        });
    }

    private const string Ns = "global::PureMarkup.Blazor.Styling";
    private const string Header = "// <auto-generated/> from Css/css.data by PureMarkup.Blazor.Generators.CssGenerator\n#nullable enable\nnamespace PureMarkup.Blazor.Styling;\n\n";

    internal static IEnumerable<(string Name, string Source)> Emit(string text)
    {
        var keywords = new List<(string Type, List<(string Css, string Cs)> Members)>();
        var props = new List<(string Css, string Cs, string? Kw, HashSet<string> Flags)>();
        foreach (var raw in text.Split('\n'))
        {
            var line = raw.Trim();
            if (line.Length == 0 || line[0] == '#') continue;
            var parts = line.Split(' ');
            if (parts[0] == "keywords")
            {
                keywords.Add((parts[1], parts.Skip(2).Select(p => { var i = p.IndexOf('='); return (p.Substring(0, i), p.Substring(i + 1)); }).ToList()));
            }
            else if (parts[0] == "prop")
            {
                var eq = parts[1].IndexOf('=');
                string? kw = null;
                var flags = new HashSet<string>(StringComparer.Ordinal);
                foreach (var p in parts.Skip(2))
                {
                    if (p.StartsWith("kw=", StringComparison.Ordinal)) kw = p.Substring(3);
                    else flags.Add(p);
                }
                props.Add((parts[1].Substring(0, eq), parts[1].Substring(eq + 1), kw, flags));
            }
        }

        var sb = new StringBuilder(Header);
        foreach (var (type, members) in keywords)
        {
            sb.Append("/// <summary>Keywords of CSS <c>").Append(type).AppendLine("</c> values. Converts to <see cref=\"CssValue\"/>.</summary>");
            sb.Append("public readonly struct ").Append(type).Append(" : ").Append(Ns).Append(".ICssValue<").Append(type).AppendLine(">").AppendLine("{");
            sb.AppendLine("    private readonly string? _css;");
            sb.Append("    private ").Append(type).AppendLine("(string css) => _css = css;");
            foreach (var (css, cs) in members)
                sb.Append("    /// <summary><c>").Append(css).Append("</c></summary>\n    public static ").Append(type).Append(' ').Append(cs).Append(" => new(\"").Append(css).AppendLine("\");");
            sb.Append("    /// <summary>Wraps CSS text.</summary>\n    public static ").Append(type).Append(" FromCss(string css) => new(css);\n");
            sb.Append("    /// <summary>To any value.</summary>\n    public static implicit operator ").Append(Ns).Append(".CssValue(").Append(type).AppendLine(" v) => new(v.ToString());");
            sb.AppendLine("    /// <inheritdoc/>\n    public override string ToString() => _css ?? \"\";");
            sb.AppendLine("}").AppendLine();
        }
        yield return ("Css.Keywords.g.cs", sb.ToString());

        sb = new StringBuilder(Header);
        sb.AppendLine("public abstract partial class CssProperties<TSelf>").AppendLine("{");
        var methods = 0;
        foreach (var (css, cs, kw, flags) in props)
        {
            void Method(string param, string value)
            {
                sb.Append("    /// <summary><c>").Append(css).AppendLine("</c></summary>");
                sb.Append("    public TSelf ").Append(cs).Append('(').Append(param).Append(") => Prop(\"").Append(css).Append("\", ").Append(value).AppendLine(");");
                methods++;
            }
            Method(Ns + ".CssValue value", "value");
            if (kw is not null) Method(Ns + "." + kw + " value", "value");
            if (flags.Contains("length")) Method(Ns + ".Length value", "value");
            if (flags.Contains("color")) Method(Ns + ".Color value", "value");
            if (flags.Contains("time")) Method(Ns + ".Time value", "value");
            if (flags.Contains("angle")) Method(Ns + ".Angle value", "value");
            if (flags.Contains("number")) Method("double value", "value");
            if (flags.Contains("multi"))
                Method(Ns + ".CssValue first, " + Ns + ".CssValue second, params global::System.ReadOnlySpan<" + Ns + ".CssValue> rest",
                    "new " + Ns + ".CssValue(Join(first, second, rest))");
        }
        sb.AppendLine("}");
        yield return ("Css.Properties.g.cs", sb.ToString());

        yield return ("Css.Counts.g.cs",
            $"// <auto-generated/>\nnamespace PureMarkup.Blazor.Styling;\n\ninternal static class CssCounts\n{{\n    public const int Properties = {props.Count};\n    public const int PropertyMethods = {methods};\n    public const int KeywordTypes = {keywords.Count};\n}}\n");
    }
}
