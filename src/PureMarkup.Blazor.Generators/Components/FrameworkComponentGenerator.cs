using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.Text;

namespace PureMarkup.Blazor.Generators.Components;

/// <summary>
/// Pack time: typed parameter methods for every public component in the referenced <c>Microsoft.AspNetCore.Components*</c>
/// assemblies, emitted into PureMarkup.Blazor itself. Runs only when that assembly is compiled; per target framework, so a
/// component that exists only in a newer framework gets methods only in that target.
/// </summary>
[Generator]
public sealed class FrameworkComponentGenerator : IIncrementalGenerator
{
    private const string LibraryAssembly = "PureMarkup.Blazor";
    private const string FrameworkPrefix = "Microsoft.AspNetCore.Components";

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var components = context.CompilationProvider.Select(static (c, ct) =>
            c.AssemblyName == LibraryAssembly ? Collect(c, ct) : default);
        context.RegisterSourceOutput(components, static (spc, list) =>
        {
            if (list.Length == 0) return;
            var methods = 0;
            foreach (var (hint, source, n) in ComponentEmitter.Emit(list, "PureMarkup.Blazor", nameof(FrameworkComponentGenerator)))
            {
                spc.AddSource(hint, SourceText.From(source, Encoding.UTF8));
                methods += n;
            }
            spc.AddSource("FrameworkComponents.Counts.g.cs", SourceText.From(
                $"// <auto-generated/>\n// components: {list.Length}, parameter methods: {methods}\nnamespace PureMarkup.Blazor;\n\n" +
                $"internal static class FrameworkComponentCounts\n{{\n    public const int Components = {list.Length};\n    public const int Methods = {methods};\n}}\n",
                Encoding.UTF8));
        });
    }

    private static EquatableArray<ComponentInfo> Collect(Compilation compilation, CancellationToken ct)
    {
        var iComponent = compilation.GetTypeByMetadataName("Microsoft.AspNetCore.Components.IComponent");
        if (iComponent is null) return default;
        var reserved = ComponentModel.ReservedNames(compilation);
        var list = new List<ComponentInfo>();
        foreach (var asm in compilation.SourceModule.ReferencedAssemblySymbols
                     .Where(a => a.Name == FrameworkPrefix || a.Name.StartsWith(FrameworkPrefix + ".", StringComparison.Ordinal))
                     .OrderBy(a => a.Name, StringComparer.Ordinal))
        {
            foreach (var t in Types(asm.GlobalNamespace))
            {
                ct.ThrowIfCancellationRequested();
                if (!ComponentModel.IsComponent(t, iComponent)) continue;
                if (ComponentModel.Read(t, compilation, reserved, ct) is { } info) list.Add(info);
            }
        }
        list.Sort((a, b) => string.CompareOrdinal(a.FullType, b.FullType));
        return new EquatableArray<ComponentInfo>(list.ToArray());
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol ns)
    {
        foreach (var t in ns.GetTypeMembers()) yield return t;
        foreach (var child in ns.GetNamespaceMembers())
            foreach (var t in Types(child)) yield return t;
    }
}
