using System.Collections.Generic;
using System.Text;

namespace PureMarkup.Blazor.Generators.Components;

/// <summary>
/// Emits typed parameter methods: one extension class per component, extending <c>ComponentNode&lt;TComponent&gt;</c>.
/// Every method calls a public <c>ComponentNode</c> method (<c>Param</c>, <c>Callback</c>, <c>Fragment</c>), so the same
/// output compiles inside the library (pack time) and in a consumer project (M2b).
/// </summary>
internal static class ComponentEmitter
{
    private const string Node = "global::PureMarkup.Blazor.Node";
    private const string Task = "global::System.Threading.Tasks.Task";

    /// <summary>Emits one source per component; returns (hint name, source, method count).</summary>
    public static IEnumerable<(string HintName, string Source, int Methods)> Emit(IEnumerable<ComponentInfo> components, string targetNamespace, string origin)
    {
        var used = new HashSet<string>();
        foreach (var c in components)
        {
            var cls = c.Name + (c.TypeParameters.Length > 0 ? "Of" + (c.TypeParameters.Split(',').Length) : "") + "Parameters";
            if (!used.Add(cls))
            {
                cls = c.Namespace.Replace(".", "") + cls;
                used.Add(cls);
            }
            var (source, methods) = EmitOne(c, cls, targetNamespace, origin);
            yield return (targetNamespace + "." + cls + ".g.cs", source, methods);
        }
    }

    private static (string Source, int Methods) EmitOne(ComponentInfo c, string cls, string ns, string origin)
    {
        var sb = new StringBuilder();
        sb.Append("// <auto-generated/> by ").AppendLine(origin);
        sb.AppendLine("#nullable enable");
        sb.Append("namespace ").Append(ns).AppendLine(";").AppendLine();
        sb.Append("/// <summary>Typed parameters of <c>").Append(Xml(c.FullType)).AppendLine("</c>.</summary>");
        if (c.HasAnnotatedMembers)
            sb.AppendLine("[global::System.Diagnostics.CodeAnalysis.UnconditionalSuppressMessage(\"Trimming\", \"IL2111\", Justification = \"ComponentNode<T> keeps all members so the renderer can set parameters; values for annotated parameters arrive through methods that carry the same annotation.\")]");
        sb.Append("public static partial class ").AppendLine(cls).AppendLine("{");

        var self = "global::PureMarkup.Blazor.ComponentNode<" + c.FullType + ">";
        var count = 0;

        void Method(string name, string doc, string paramDecl, string body)
        {
            sb.Append("    /// <summary>").Append(doc).AppendLine("</summary>");
            sb.Append("    public static ").Append(self).Append(' ').Append(name).Append(c.TypeParameters)
              .Append("(this ").Append(self).Append(" c, ").Append(paramDecl).Append(')').Append(c.Constraints)
              .Append(" => ").Append(body).AppendLine(";");
            count++;
        }

        foreach (var p in c.Params)
        {
            var doc = "<c>" + p.Name + "</c> parameter.";
            var name = "\"" + p.Name + "\"";
            switch (p.Kind)
            {
                case ParamKind.Value:
                    Method(p.Method, doc, p.ParamAttributes + p.Type + " value", "c.Param(" + name + ", value)");
                    break;
                case ParamKind.Event:
                    doc = "<c>" + p.Name + "</c> event callback; the receiver is the component that renders this markup.";
                    Method(p.Method, doc, "global::System.Action handler", "c.Callback(" + name + ", handler)");
                    Method(p.Method, doc, "global::System.Func<" + Task + "> handler", "c.Callback(" + name + ", handler)");
                    Method(p.Method, doc, "global::Microsoft.AspNetCore.Components.EventCallback callback", "c.Param(" + name + ", callback)");
                    break;
                case ParamKind.EventOf:
                    doc = "<c>" + p.Name + "</c> event callback; the receiver is the component that renders this markup.";
                    var cb = "c.Callback<" + p.Type + ">(" + name + ", handler)";
                    Method(p.Method, doc, "global::System.Action handler", cb);
                    Method(p.Method, doc, "global::System.Action<" + p.Type + "> handler", cb);
                    Method(p.Method, doc, "global::System.Func<" + Task + "> handler", cb);
                    Method(p.Method, doc, "global::System.Func<" + p.Type + ", " + Task + "> handler", cb);
                    Method(p.Method, doc, "global::Microsoft.AspNetCore.Components.EventCallback<" + p.Type + "> callback", "c.Param(" + name + ", callback)");
                    break;
                case ParamKind.Fragment:
                    doc = "<c>" + p.Name + "</c> fragment, built when the component renders it.";
                    Method(p.Method, doc, "global::System.Func<" + Node + "> content", "c.Fragment(" + name + ", content)");
                    Method(p.Method, "<c>" + p.Name + "</c> fragment that is plain text.", "string? text", "c.Fragment(" + name + ", text)");
                    break;
                case ParamKind.FragmentOf:
                    doc = "<c>" + p.Name + "</c> fragment, built when the component renders it.";
                    Method(p.Method, doc, "global::System.Func<" + p.Type + ", " + Node + "> content", "c.Fragment<" + p.Type + ">(" + name + ", content)");
                    break;
            }
        }
        if (c.CapturesUnmatched)
            Method("Attr", "An attribute the component captures (<c>CaptureUnmatchedValues</c>), as Razor's unmatched attributes.",
                "string name, object? value", "c.Param(name, value)");

        sb.AppendLine("}");
        return (sb.ToString(), count);
    }

    private static string Xml(string s) => s.Replace("&", "&amp;").Replace("<", "&lt;").Replace(">", "&gt;");
}
