using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp.Syntax;
using Microsoft.CodeAnalysis.Text;

namespace PureMarkup.Blazor.Generators.Components;

/// <summary>
/// Consumer time: typed parameter methods for components the library does not cover, emitted as <c>internal</c> classes into the
/// project being compiled. Sources: <c>[assembly: GenerateMarkup(typeof(X))]</c> (one component, or its whole assembly) and every
/// concrete C# component declared in the project. <c>.razor</c> components come from another generator, so they are not
/// visible here and keep using <c>.Param</c>.
/// </summary>
[Generator]
public sealed class ConsumerComponentGenerator : IIncrementalGenerator
{
    private const string LibraryAssembly = "PureMarkup.Blazor";
    private const string AttributeName = "PureMarkup.Blazor.GenerateMarkupAttribute";
    private const string DefaultNamespace = "PureMarkup.Blazor";

    private static DiagnosticDescriptor Create(string id, string title, string format) =>
        new(id, title, format, "PureMarkup", DiagnosticSeverity.Warning, isEnabledByDefault: true);

    internal static readonly DiagnosticDescriptor NotComponent = Create(
        "PMCOMP001", "GenerateMarkup type is not a component",
        "'{0}' is not a concrete component (a non-abstract class implementing IComponent); no parameter methods generated");

    internal static readonly DiagnosticDescriptor NotAccessible = Create(
        "PMCOMP002", "GenerateMarkup type is not accessible",
        "'{0}' is not accessible from this project (it must be public, or internal to this project); no parameter methods generated");

    internal static readonly DiagnosticDescriptor AlreadyCovered = Create(
        "PMCOMP003", "GenerateMarkup type is already covered",
        "'{0}' already has typed parameter methods in PureMarkup.Blazor; remove the attribute");

    public void Initialize(IncrementalGeneratorInitializationContext context)
    {
        var fromAttributes = context.CompilationProvider.Select(static (c, ct) => FromAttributes(c, ct));

        var local = context.SyntaxProvider.CreateSyntaxProvider(
                static (node, _) => node is ClassDeclarationSyntax { BaseList: not null },
                static (ctx, ct) => FromLocal(ctx, ct))
            .Where(static x => x is not null)
            .Collect();

        context.RegisterSourceOutput(fromAttributes.Combine(local), static (spc, pair) =>
        {
            var (attrs, locals) = pair;
            foreach (var d in attrs.Diagnostics) spc.ReportDiagnostic(Diagnostic.Create(d.Descriptor, d.Location, d.Arg));

            var seen = new HashSet<string>(StringComparer.Ordinal);
            var groups = new Dictionary<string, List<ComponentInfo>>(StringComparer.Ordinal);
            void Add(string ns, ComponentInfo c)
            {
                if (!seen.Add(c.FullType) || (c.Params.Length == 0 && !c.CapturesUnmatched)) return;
                if (!groups.TryGetValue(ns, out var list)) groups[ns] = list = new List<ComponentInfo>();
                list.Add(c);
            }
            foreach (var (ns, c) in attrs.Components) Add(ns, c);
            foreach (var c in locals.OrderBy(c => c!.FullType, StringComparer.Ordinal)) Add(DefaultNamespace, c!);

            int components = 0, methods = 0;
            foreach (var g in groups.OrderBy(g => g.Key, StringComparer.Ordinal))
                foreach (var (hint, source, n) in ComponentEmitter.Emit(g.Value, g.Key, nameof(ConsumerComponentGenerator), consumer: true))
                {
                    spc.AddSource(hint, SourceText.From(source, Encoding.UTF8));
                    components++;
                    methods += n;
                }
            if (components > 0)
                spc.AddSource("ConsumerComponents.Counts.g.cs", SourceText.From(
                    $"// <auto-generated/>\n// components: {components}, parameter methods: {methods}\n", Encoding.UTF8));
        });
    }

    private static ComponentInfo? FromLocal(GeneratorSyntaxContext ctx, CancellationToken ct)
    {
        var compilation = ctx.SemanticModel.Compilation;
        if (compilation.AssemblyName == LibraryAssembly) return null;
        if (ctx.SemanticModel.GetDeclaredSymbol(ctx.Node, ct) is not INamedTypeSymbol type) return null;
        var iComponent = compilation.GetTypeByMetadataName("Microsoft.AspNetCore.Components.IComponent");
        if (iComponent is null || compilation.GetTypeByMetadataName(ComponentModel.ComponentNodeMetadataName) is null) return null;
        // A partial class is seen once per declaration with a base list; read it at the first such one only.
        var first = type.DeclaringSyntaxReferences.Select(r => r.GetSyntax(ct)).OfType<ClassDeclarationSyntax>().First(d => d.BaseList is not null);
        if (first != ctx.Node) return null;
        if (!ComponentModel.IsComponent(type, iComponent, compilation, compilation.Assembly)) return null;
        return ComponentModel.Read(type, compilation, ComponentModel.ReservedNames(compilation), ct, compilation.Assembly);
    }

    private static AttributeResult FromAttributes(Compilation compilation, CancellationToken ct)
    {
        if (compilation.AssemblyName == LibraryAssembly) return AttributeResult.Empty;
        var attr = compilation.GetTypeByMetadataName(AttributeName);
        var iComponent = compilation.GetTypeByMetadataName("Microsoft.AspNetCore.Components.IComponent");
        if (attr is null || iComponent is null) return AttributeResult.Empty;

        var requests = compilation.Assembly.GetAttributes()
            .Where(a => SymbolEqualityComparer.Default.Equals(a.AttributeClass, attr) && a.ConstructorArguments.Length == 1)
            .ToList();
        if (requests.Count == 0) return AttributeResult.Empty;

        var reserved = ComponentModel.ReservedNames(compilation);
        var covered = ComponentModel.CoveredByLibrary(compilation);
        var within = compilation.Assembly;
        var components = new List<(string, ComponentInfo)>();
        var diagnostics = new List<DiagnosticInfo>();
        var done = new HashSet<INamedTypeSymbol>(SymbolEqualityComparer.Default);

        void Generate(INamedTypeSymbol t, string ns)
        {
            if (done.Add(t) && ComponentModel.Read(t, compilation, reserved, ct, within) is { } info) components.Add((ns, info));
        }

        foreach (var a in requests)
        {
            ct.ThrowIfCancellationRequested();
            if (a.ConstructorArguments[0].Value is not INamedTypeSymbol named) continue;
            var type = named.OriginalDefinition;
            var whole = a.NamedArguments.Any(kv => kv.Key == "WholeAssembly" && kv.Value.Value is true);
            var ns = a.NamedArguments.FirstOrDefault(kv => kv.Key == "Namespace").Value.Value as string;
            if (string.IsNullOrWhiteSpace(ns)) ns = DefaultNamespace;
            var location = a.ApplicationSyntaxReference?.GetSyntax(ct).GetLocation();
            var display = type.ToDisplayString();

            if (whole)
            {
                foreach (var t in Types(type.ContainingAssembly.GlobalNamespace))
                {
                    ct.ThrowIfCancellationRequested();
                    if (!covered.Contains(t) && ComponentModel.IsComponent(t, iComponent, compilation, within)) Generate(t, ns!);
                }
                continue;
            }
            if (!ComponentModel.IsConcreteComponent(type, iComponent)) diagnostics.Add(new(NotComponent, location, display));
            else if (!compilation.IsSymbolAccessibleWithin(type, within)) diagnostics.Add(new(NotAccessible, location, display));
            else if (covered.Contains(type)) diagnostics.Add(new(AlreadyCovered, location, display));
            else Generate(type, ns!);
        }
        components.Sort((x, y) => string.CompareOrdinal(x.Item2.FullType, y.Item2.FullType));
        return new AttributeResult(new EquatableArray<NsComponent>(components.Select(c => new NsComponent(c.Item1, c.Item2)).ToArray()),
            new EquatableArray<DiagnosticInfo>(diagnostics.ToArray()));
    }

    private static IEnumerable<INamedTypeSymbol> Types(INamespaceSymbol ns)
    {
        foreach (var t in ns.GetTypeMembers())
        {
            yield return t;
            foreach (var nested in Nested(t)) yield return nested;
        }
        foreach (var child in ns.GetNamespaceMembers())
            foreach (var t in Types(child)) yield return t;
    }

    private static IEnumerable<INamedTypeSymbol> Nested(INamedTypeSymbol t)
    {
        foreach (var n in t.GetTypeMembers())
        {
            yield return n;
            foreach (var m in Nested(n)) yield return m;
        }
    }

    private sealed record NsComponent(string Namespace, ComponentInfo Component)
    {
        public void Deconstruct(out string ns, out ComponentInfo c) { ns = Namespace; c = Component; }
    }

    private sealed record DiagnosticInfo(DiagnosticDescriptor Descriptor, Location? Location, string Arg);

    private sealed record AttributeResult(EquatableArray<NsComponent> Components, EquatableArray<DiagnosticInfo> Diagnostics)
    {
        public static readonly AttributeResult Empty = new(default, default);
    }
}
