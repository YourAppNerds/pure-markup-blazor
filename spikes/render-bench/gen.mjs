// Generates Baseline/Page200.razor and Bench/MarkupPage200*.cs from one spec, so both render the same page.
import { writeFileSync } from 'node:fs';
const N = 9;
const razor = ['@* Generated by gen.mjs. *@', '@inherits BenchBase', '@implements IBenchTarget', '<main class="page">'];
const cs = (stat) => {
  const out = [];
  for (let i = 1; i <= N; i++) {
    const lead = `P().Class("lead").Children(Text("Intro text for section ${i} with a "), Span().Class("hl").Text("highlight"), Text("."))`;
    const ul = `Ul().Class("links").Children(${['a', 'b', 'c', 'd'].map(x => `Li().Children(A().Attr("href", "/s${i}/${x}").Text("Link ${x.toUpperCase()}"))`).join(', ')})`;
    out.push(`            Section().Class("card").Id("s${i}").Children(
                H2().Class("title").Children(Text("Section ${i}: "), Text(Title)),
                ${stat ? `Static(static () => ${lead})` : lead},
                ${stat ? `Static(static () => ${ul})` : ul},
                Div().Class(Active == ${i} ? "row active" : "row").Children(
                    Button().Attr("type", "button").Class("btn").OnClick(() => Click(${i})).Text("Open ${i}"),
                    Comp<Badge>().Param("Label", "S${i}").Param("Count", Count),
                    Span().Class("count").Text(Count)),
                If(ShowExtra, () => P().Class("extra").Text("Extra details for section ${i}.")),
                Img().Attr("src", "/img/${i}.png").Attr("alt", "Image ${i}"),
                Input().Attr("type", "text").Attr("placeholder", "Name ${i}").Attr("value", Name),
                P().Class("foot").Children(Text("Updated by "), Text(Name)))`);
  }
  return out.join(',\n');
};
for (let i = 1; i <= N; i++) {
  razor.push(
    `<section class="card" id="s${i}">`,
    `    <h2 class="title">Section ${i}: @Title</h2>`,
    `    <p class="lead">Intro text for section ${i} with a <span class="hl">highlight</span>.</p>`,
    `    <ul class="links">`,
    ...['a', 'b', 'c', 'd'].map(x => `        <li><a href="/s${i}/${x}">Link ${x.toUpperCase()}</a></li>`),
    `    </ul>`,
    `    <div class="@(Active == ${i} ? "row active" : "row")">`,
    `        <button type="button" class="btn" @onclick="() => Click(${i})">Open ${i}</button>`,
    `        <Badge Label="S${i}" Count="@Count" />`,
    `        <span class="count">@Count</span>`,
    `    </div>`,
    `    @if (ShowExtra)`, `    {`, `        <p class="extra">Extra details for section ${i}.</p>`, `    }`,
    `    <img src="/img/${i}.png" alt="Image ${i}" />`,
    `    <input type="text" placeholder="Name ${i}" value="@Name" />`,
    `    <p class="foot">Updated by @Name</p>`,
    `</section>`);
}
razor.push('</main>', '@code {',
  '    public string Title { get; set; } = "Dashboard & <stuff>";',
  '    public int Active { get; set; } = 1;',
  '    public int Count { get; set; } = 3;',
  '    public string Name { get; set; } = "Kyle";',
  '    public bool ShowExtra { get; set; } = true;',
  '    public void Click(int i) => Active = i;',
  '    public void Toggle() => Active = Active == 1 ? 2 : 1;',
  '}', '');
writeFileSync('Baseline/Page200.razor', razor.join('\n'));
for (const stat of [false, true]) {
  const name = stat ? 'MarkupPage200Static' : 'MarkupPage200';
  writeFileSync(`Bench/${name}.cs`, `// Generated by gen.mjs.
using Baseline;
using PureMarkup.Prototype;
using static PureMarkup.Prototype.H;

namespace Bench;

public sealed class ${name} : MarkupComponent, IBenchTarget
{
    public string Title { get; set; } = "Dashboard & <stuff>";
    public int Active { get; set; } = 1;
    public int Count { get; set; } = 3;
    public string Name { get; set; } = "Kyle";
    public bool ShowExtra { get; set; } = true;
    public void Click(int i) => Active = i;
    public void Toggle() => Active = Active == 1 ? 2 : 1;

    protected override Node Render() =>
        Main().Class("page").Children(
${cs(stat)});
}
`);
}
console.log('razor lines:', razor.length);
